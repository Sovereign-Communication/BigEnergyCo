/**
 * Fold a country string to a comparable key.
 *
 * Deliberately lossy and deliberately small: case, accents and punctuation go,
 * because they differ between the catalogue, the partitions and the geocoder
 * and carry no currency meaning. Diacritics are folded rather than kept, so
 * "Turkiye" and "Türkiye" agree.
 */
export function normalizeCountry(name) {
  return String(name ?? "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[.'’,]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * The ISO 4217 currency for a country, or null when it is not known.
 *
 * Accepts either form the app carries: an ISO 3166-1 alpha-2 code (the city
 * partitions) or a country name (the seed catalogue, reverse geocoding, the
 * Tariff boxes). Null is an honest answer and the caller falls back to the
 * box's currency -- but null now means "we do not know this country", not "we
 * guessed and got it wrong".
 */
export function currencyForCountry(country) {
  const raw = String(country ?? "").trim();
  if (!raw) return null;

  // An alpha-2 code is exact: no lookup table, no spelling to disagree about.
  const upper = raw.toUpperCase();
  if (/^[A-Z]{2}$/.test(upper) && COUNTRY_CURRENCY[upper])
    return COUNTRY_CURRENCY[upper];

  return COUNTRY_CURRENCY[COUNTRY_NAMES[normalizeCountry(raw)]] ?? null;
}
