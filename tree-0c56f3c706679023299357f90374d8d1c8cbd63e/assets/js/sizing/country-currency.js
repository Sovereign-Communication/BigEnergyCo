// Country -> currency, exactly.
//
// Why this file exists. The tariff boxes in pricing.js carry a `currency`, and
// they are GEOGRAPHIC: one box covers several countries. "United Kingdom /"
// "Ireland" is a single box and it says GBP, so picking Dublin produced pounds.
// "Australia / New Zealand" says AUD, so Wellington produced Australian dollars.
// "Peru / Ecuador" says PEN, so Quito -- a country that does not use the sol at
// all -- produced Peruvian soles. The same shape silently mispriced Czechia
// (PLN), Slovakia, Uruguay (CLP), Venezuela, South Korea (JPY), Jordan (ILS),
// Algeria, Tunisia, Libya, Sudan, Uganda, Tanzania, Rwanda, Namibia, Botswana,
// Pakistan, Bangladesh, Nepal, Myanmar, Laos, and every country in the Gulf and
// in the multi-currency Africa boxes, which carry `null` and fell through to
// USD. Roughly forty countries, each showing a visitor a currency their own
// country does not use, with no error anywhere to notice it by.
//
// The fix is not a better guess from coordinates. Every location this app can
// resolve already knows its country: the per-country city partitions carry
// ISO 3166-1 alpha-2, and the seed catalogue and reverse geocoder carry a
// name. So the currency is a lookup, not an inference -- and a lookup can be
// checked, which an inference cannot.
//
// Keys are ISO 3166-1 alpha-2 -> ISO 4217. This table covers exactly the
// countries the shipped city data contains; tests/currency-coverage.test.mjs
// fails if a partition appears that is not listed here, so a newly added
// country cannot slip through as an unhandled fallback to USD.

