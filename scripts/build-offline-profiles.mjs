// Generates assets/js/sizing/profiles.js — bundled typical-year weather for
// every city preset, so the full sizer works with ZERO network after first
// load (and on offline mode). Run: node scripts/build-offline-profiles.mjs
// Fetches 1 year of hourly NASA POWER per city (~66 requests, a few minutes).
import { writeFileSync } from "node:fs";
import {
  CITY_PRESETS,
  fetchHourlySeries,
  buildUrl,
  parseHourly,
} from "../assets/js/sizing/nasa.js";

const round1 = (x) => Math.round(x * 10) / 10;

async function fetchYear(lat, lon) {
  // Most recent complete year.
  const endYear = new Date().getUTCFullYear() - 1;
  const url = buildUrl(lat, lon, `${endYear}0101`, `${endYear}1231`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`POWER ${res.status} for ${lat},${lon}`);
  const json = await res.json();
  return { hours: parseHourly(json), year: endYear };
}

function monthOfDay(doy) {
  // Non-leap typical year.
  const starts = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334, 365];
  for (let m = 11; m >= 0; m--) if (doy >= starts[m]) return m;
  return 0;
}

console.log(`Building offline profiles for ${CITY_PRESETS.length} cities…`);
const out = [];
let done = 0;
for (const city of CITY_PRESETS) {
  const { hours, year } = await fetchYear(city.lat, city.lon);
  // ghi[month][hour], tAmb[month][hour] — means across all days of that month.
  const ghi = Array.from({ length: 12 }, () => Array(24).fill(0));
  const tAmb = Array.from({ length: 12 }, () => Array(24).fill(0));
  const n = Array.from({ length: 12 }, () => Array(24).fill(0));
  for (let i = 0; i < hours.length; i++) {
    const doy = Math.floor(i / 24);
    const m = monthOfDay(doy);
    const h = i % 24;
    const rec = hours[i];
    if (Number.isFinite(rec.ghi)) {
      ghi[m][h] += rec.ghi;
      n[m][h]++;
    }
    if (Number.isFinite(rec.tAmb)) tAmb[m][h] += rec.tAmb;
  }
  const G = ghi.map((row, m) =>
    row.map((v, h) => (n[m][h] ? Math.round(v / n[m][h]) : 0)),
  );
  const T = tAmb.map((row, m) =>
    row.map((v, h) => (n[m][h] ? round1(v / n[m][h]) : 15)),
  );
  out.push({
    name: city.name,
    lat: +city.lat.toFixed(2),
    lon: +city.lon.toFixed(2),
    ghi: G,
    tAmb: T,
  });
  done++;
  console.log(
    `  [${done}/${CITY_PRESETS.length}] ${city.name} (${year}, mean GHI ${(G.flat().reduce((a, b) => a + b, 0) / 12 / 1000).toFixed(2)} kWh/m²/day)`,
  );
}

const banner = `// AUTO-GENERATED by scripts/build-offline-profiles.mjs — do not edit by hand.
// Typical-year hourly GHI (W/m²) and ambient temperature (°C) means per
// month/hour for every city preset, from NASA POWER hourly data. Enables the
// full deterministic sizer with zero network (PWA offline + offline mode).
export const PROFILE_YEAR = ${out[0] ? new Date().getUTCFullYear() - 1 : "null"};

`;

const body = "export const OFFLINE_PROFILES = " + JSON.stringify(out) + ";\n";
writeFileSync(
  new URL("../assets/js/sizing/profiles.js", import.meta.url),
  banner + body,
);
console.log(
  `\nWrote assets/js/sizing/profiles.js (${Math.round(Buffer.byteLength(banner + body) / 1024)} KB)`,
);
