#!/usr/bin/env node
// Build the `audit-sim` fixture: a throwaway repository whose tip is a
// FABRICATED `Merge pull request #N from Sovereign-Communication/pr-sim`
// commit, used to exercise `scripts/direct-push-audit.mjs` and
// `prDeliveredShas` (scripts/lib/release.mjs) against the one shape those
// guards cannot tell from a real GitHub merge.
//
// WHY THIS IS COMMITTED. `C:/tmp/audit-sim` and `C:/tmp/audit-sim3` were
// described as "reproducible scaffolding" in the 2026-11-03 preservation
// record, but no generator was ever committed, so the claim rested on two
// directories on one machine and GitHub rejects their tips (HTTP 422). Row G6
// of docs/lane/PRESERVATION-CONFORMANCE-2026-11-05.md therefore scored as a
// gap: asserted-regenerable, not proven. This file is the generator, and
// tests/audit-sim-fixture.test.mjs runs it, so the fixture is now proven
// regenerable rather than asserted to be.
//
// The fixture is DETERMINISTIC: fixed identities, fixed timestamps, fixed
// content and a fixed default branch, so the same generator produces the same
// object graph (and the same tip SHA) on any machine with git. A caller that
// needs a different tip reproduces it by changing `--pr` or the seed file,
// not by editing this script.
//
// Usage:
//   node scripts/make-audit-sim-fixture.mjs --dir <path> [--pr 9999] [--seed extra]
//
// The directory must be absent or empty; this script never writes into a
// directory it did not create, so a mistyped --dir cannot touch real work.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const DATE = "2026-10-23T00:00:00 +0000";

const arg = (flag, fallback = null) => {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : fallback;
};

const dir = resolve(arg("--dir") || "./audit-sim");
const pr = String(arg("--pr", "9999"));
const seed = String(arg("--seed", ""));

if (existsSync(dir) && readdirSync(dir).length) {
  console.error(
    `REFUSED: ${dir} exists and is not empty. This generator only writes into a directory it creates.`,
  );
  process.exit(2);
}
if (!/^\d+$/.test(pr)) {
  console.error("REFUSED: --pr must be a PR number (digits only).");
  process.exit(2);
}

const envFor = (iso) => ({
  ...process.env,
  GIT_AUTHOR_DATE: iso,
  GIT_COMMITTER_DATE: iso,
  GIT_AUTHOR_NAME: "pr-sim",
  GIT_AUTHOR_EMAIL: "noreply@github.com",
  GIT_COMMITTER_NAME: "pr-sim",
  GIT_COMMITTER_EMAIL: "noreply@github.com",
});

/** Run git in the fixture with a fixed clock, so the object graph is stable. */
const git = (args, iso = DATE) =>
  execFileSync("git", args, {
    cwd: dir,
    env: envFor(iso),
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
  }).trim();

const write = (file, body) => {
  mkdirSync(join(dir, file, ".."), { recursive: true });
  writeFileSync(join(dir, file), body);
};

const commit = (message, iso) => {
  git(["add", "-A"]);
  git(["commit", "-q", "-m", message], iso);
  return git(["rev-parse", "HEAD"]);
};

mkdirSync(dir, { recursive: true });
git(["init", "-q", "-b", "main", "."]);

// Base: documentation only, so the fixture starts as a clean state.
write(
  "README.md",
  "# audit-sim fixture\n\nSynthetic. Generated by scripts/make-audit-sim-fixture.mjs.\n",
);
commit("base", "2026-10-23T00:00:00 +0000");

// A branch carrying a NON-documentation change: the file whose presence in a
// fabricated merge is what makes the fixture useful.
git(["switch", "-q", "-c", "pr-sim"]);
write(
  "assets/js/sim.js",
  `// Synthetic fixture file, not part of the shipped site.\nexport const fixtureSeed = ${JSON.stringify(seed)};\n`,
);
const pulled = commit(
  "pr-sim: change a non-documentation file",
  "2026-10-23T00:01:00 +0000",
);

// The lie the fixture exists to reproduce: a merge subject naming a PR that
// never existed. GitHub would not create this commit; `git merge --no-ff` will.
git(["switch", "-q", "main"]);
git(
  [
    "merge",
    "--no-ff",
    "-q",
    "-m",
    `Merge pull request #${pr} from Sovereign-Communication/pr-sim`,
    "pr-sim",
  ],
  "2026-10-23T00:02:00 +0000",
);

const tip = git(["rev-parse", "HEAD"]);
const subject = git(["log", "-1", "--format=%s"]);

process.stdout.write(
  [
    `audit-sim fixture: ${dir}`,
    `tip: ${tip}`,
    `subject: ${subject}`,
    `pulled commit: ${pulled}`,
    `fabricated PR: #${pr}`,
    "",
  ].join("\n"),
);
