// Single owner of the deploy contract: which files ship to production.
//
// Enumeration reads git's index (`git ls-files`), never the working tree. The
// index is immutable metadata captured by actions/checkout, so a transient
// filesystem state — a partially generated tree, a failed build step, an CI
// cache hiccup — cannot silently shrink the artifact the gates verify. This
// is the root-cause fix for the 259-vs-353 enumeration flake: a filesystem
// walk reflects whatever happens to be on disk at that instant; the index
// does not. Generated outputs (solar-calculator/* city pages) are committed,
// so they are covered by the index like everything else.
//
// Consumers: deploy-pages-local.mjs (staging build + gh-pages push),
// scripts/lib/gates.mjs (deployedFiles, via `--list` stdout), and the
// release verifier. The `--list` output format is byte-compatible with the
// old walker, so no consumer changed.
import { execSync } from "node:child_process";
import { join, resolve } from "node:path";

export const ROOT = resolve(
  new URL("../..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"),
);

export const ALLOWLIST = [
  "index.html",
  "404.html",
  "robots.txt",
  "sitemap.xml",
  "rss.xml",
  "llms.txt",
  "sw.js",
  "manifest.webmanifest",
  "_headers",
  "_redirects",
  "styles.css",
  "blog/index.html",
  "blog/diy-vs-prebuilt-sodium-ion-lifepo4-battery-storage/index.html",
  "blog/off-grid-vs-grid-tie-payback/index.html",
  "blog/how-to-cut-electricity-bill-with-solar/index.html",
  "blog/is-a-home-battery-worth-it/index.html",
  "blog/time-of-use-tariffs-battery/index.html",
  "blog/what-size-solar-system-for-off-grid/index.html",
  "blog/off-grid-battery-bank-sizing/index.html",
  "blog/solar-vs-generator-cost/index.html",
  "blog/escape-load-shedding/index.html",
  "blog/battery-longevity-and-dod-reference/index.html",
  "about/index.html",
  "solar-calculator", // copied recursively (hub + 66 city pages, generated by scripts/build-city-pages.mjs)
  "solar-heatmap", // copied recursively (interactive world map)
  "assets", // copied recursively (og-card.jpg + js/sizing/*, including city data)
];

// Top-level guard: nothing may be published outside the expected site dirs.
export const allowedTop = new Set([
  "index.html",
  "404.html",
  "robots.txt",
  "sitemap.xml",
  "rss.xml",
  "llms.txt",
  "sw.js",
  "manifest.webmanifest",
  "_headers",
  "_redirects",
  "styles.css",
  "blog",
  "about",
  "solar-calculator",
  "solar-heatmap",
  "assets",
]);
for (const entry of ALLOWLIST)
  if (!allowedTop.has(entry.split("/")[0]))
    throw new Error(`Allowlist entry outside the expected dirs: ${entry}`);

/** Files git tracks, as an absolute-path-keyed set of repo-relative paths. */
export function trackedFiles() {
  const out = execSync("git ls-files -z", {
    cwd: ROOT,
    maxBuffer: 32 * 1024 * 1024,
    encoding: "utf8",
  });
  return new Set(out.split("\0").filter(Boolean));
} /**
 * The deploy contract: every file that ships, in ALLOWLIST order. Derived
 * entirely from the git index — NOT from the working tree or a directory
 * walk — so the list is identical in a fresh checkout, in CI, and on a
 * machine mid-build, and a working-tree deletion cannot shrink it (the
 * index still names the file; the copy step then fails loudly on the one
 * missing source instead of silently shipping a smaller site).
 */
export function deployList() {
  const tracked = trackedFiles();
  const list = [];
  for (const entry of ALLOWLIST) {
    if (tracked.has(entry)) {
      list.push(entry);
      continue;
    }
    const prefix = entry.endsWith("/") ? entry : entry + "/";
    const under = [...tracked].filter((f) => f.startsWith(prefix));
    if (under.length === 0)
      throw new Error(`Allowlist entry matches nothing tracked: ${entry}`);
    list.push(...under);
  }
  return list;
}
